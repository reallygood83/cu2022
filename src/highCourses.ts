/** 계열 파일 기반 폴백: 접두 매핑이 없어도 계열·교과는 교정 */
const SOURCE_FALLBACKS: Array<{ test: RegExp; subject: string; track: CourseTrack }> = [
  { test: /과학 계열/, subject: "과학", track: "전문(계열)" },
  { test: /체육 계열/, subject: "체육", track: "전문(계열)" },
  { test: /예술 계열/, subject: "예술", track: "전문(계열)" },
];

/** 성취기준 코드에서 과목 접두 추출 (예: 12미적Ⅰ-01-01 → 12미적Ⅰ) */
export function highCoursePrefix(code: string): string | undefined {
  const m = code.match(/^(1[0-3])([가-힣ⅠⅡⅢ]+)/);
  return m ? m[1] + m[2] : undefined;
}

/** 코드+출처파일(+본문)로 과목 정보 결정 */
export function highCourseFor(
  code: string,
  sourceFile?: string,
  text?: string,
): (Entry & { fallback?: boolean }) | undefined {
  const prefix = highCoursePrefix(code);
  if (!prefix) return undefined;
  const src = sourceFile ?? "";
  const overrides = BY_SOURCE_OVERRIDES.filter((o) => o.prefix === prefix);
  if (overrides.length) {
    for (const o of overrides) if (o.test.test(src)) return o.info;
    if (text) {
      for (const o of overrides) if (o.textTest?.test(text)) return o.info;
    }
    return overrides[0].info;
  }
  const direct = HIGH_COURSE_BY_PREFIX[prefix];
  if (direct) return direct;
  for (const f of SOURCE_FALLBACKS) {
    if (f.test.test(src)) {
      return { course: "", subject: f.subject, track: f.track, fallback: true };
    }
  }
  return undefined;
}

interface AliasHit {
  alias: string;
  prefixes: string[];
  subject: string;
}

/** 별칭 인덱스 (긴 별칭 우선 매칭) */
const ALIAS_INDEX: AliasHit[] = (() => {
  const map = new Map<string, { prefixes: Set<string>; subject: string }>();
  const add = (alias: string, prefix: string, subject: string) => {
    const key = alias.replace(/\s+/g, "");
    if (key.length < 2) return;
    const e = map.get(key) ?? { prefixes: new Set<string>(), subject };
    e.prefixes.add(prefix);
    map.set(key, e);
  };
  for (const [prefix, info] of Object.entries(HIGH_COURSE_BY_PREFIX)) {
    add(info.course, prefix, info.subject);
    for (const a of info.aliases ?? []) add(a, prefix, info.subject);
  }
  for (const o of BY_SOURCE_OVERRIDES) {
    add(o.info.course, o.prefix, o.info.subject);
    for (const a of o.info.aliases ?? []) add(a, o.prefix, o.info.subject);
  }
  // 광역 교과명과 동일한 별칭은 초·중 검색 오염 방지를 위해 추론에서 제외
  const generic = new Set([
    "국어", "수학", "영어", "과학", "사회", "도덕", "체육", "음악", "미술",
    "정보", "한문", "교양",
  ]);
  return [...map.entries()]
    .filter(([alias]) => !generic.has(alias))
    .map(([alias, e]) => ({ alias, prefixes: [...e.prefixes], subject: e.subject }))
    .sort((a, b) => b.alias.length - a.alias.length);
})();

export interface CourseInference {
  prefixes: string[];
  courses: string[];
  subject?: string;
  matchedAlias: string;
}

/**
 * 질의에서 고교 선택과목 추론.
 * 초·중 학교급 힌트가 있으면 추론하지 않는다 (예: "중2 기하").
 */
export function inferHighCourseFromQuery(query: string): CourseInference | undefined {
  const q = query.replace(/\s+/g, "");
  if (!q) return undefined;
  if (/초등|초[1-6]\b|[1-6]학년|중등|중학|중[1-3]\b|elementary|middle/i.test(query)) {
    return undefined;
  }
  for (const hit of ALIAS_INDEX) {
    if (q.includes(hit.alias)) {
      const courses = [
        ...new Set(
          hit.prefixes
            .map((p) => HIGH_COURSE_BY_PREFIX[p]?.course)
            .filter((c): c is string => Boolean(c)),
        ),
      ];
      return {
        prefixes: hit.prefixes,
        courses: courses.length ? courses : [hit.alias],
        subject: hit.subject,
        matchedAlias: hit.alias,
      };
    }
  }
  return undefined;
}
